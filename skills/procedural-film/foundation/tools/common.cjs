// Photographs are the one sanctioned media, and only through the two doors that put them there: the
// generated src/photos.js section, and core's own loader lines marked photo-io. A marker copied into
// a scene file exempts nothing — the scope check below is on the file, not just the comment.
function scanForbidden(html) {
  const hits = [];
  const lines = html.split('\n');
  const exempt = new Set();
  let inPhotos = false;
  let inCore = false;
  for (let i = 0; i < lines.length; i++) {
    const head = lines[i].startsWith('// ---- ') ? lines[i].slice(8).replace(/\\/g, '/') : null;
    if (head !== null) {
      inPhotos = head === 'src/photos.js';
      inCore = head === 'src/core.js';
    } else if (lines[i] === '</script>') {
      inPhotos = false;
      inCore = false;
    }
    if (inPhotos || (inCore && lines[i].includes('/* photo-io */'))) exempt.add(i);
  }
  for (const f of FORBIDDEN) {
    for (let i = 0; i < lines.length; i++) {
      if (exempt.has(i)) continue;
      f.re.lastIndex = 0;
      let m;
      while ((m = f.re.exec(lines[i]))) {
        const col = m.index;
        hits.push({ pattern: f.name, line: i + 1, text: lines[i].slice(Math.max(0, col - 40), col + 60).trim() });
        if (!f.re.global) break;
      }
    }
  }
  return hits;
}

